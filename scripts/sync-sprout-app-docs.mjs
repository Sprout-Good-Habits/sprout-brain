#!/usr/bin/env node
// Regenerate the docs in this repo that are COPIES of sprout-app's live
// contract, by fetching them from the Sprout server's public guides endpoint.
//
//   Sync:   node scripts/sync-sprout-app-docs.mjs
//   Check:  node scripts/sync-sprout-app-docs.mjs --check    (exit 1 if stale)
//   Other server: --base https://api.stage.example.com
//
// WHY THIS EXISTS
//   Most of this repo is original: boards.md, worked-patterns.md, design/,
//   knowledge/, skills/, examples/. A few files are not — they describe what
//   the deployed Sprout server actually accepts, and sprout-app is upstream.
//   Those were kept by hand, and `canvas/sdk.md` drifted 557 lines behind
//   before anyone noticed: whole released SDK surfaces were missing from the
//   copy an installed plugin was teaching people to build against.
//
//   The server now serves those documents itself, off the same registry that
//   answers MCP `resources/read` — so the public URL cannot disagree with the
//   running server. This script makes our copy a derivative of that URL
//   instead of a parallel document.
//
//   It reads a PUBLIC endpoint, so it needs no sprout-app checkout and no
//   credentials at all. In CI the only token involved is the default
//   same-repo GITHUB_TOKEN used to commit the result.
//
// WHAT IS NOT SYNCED
//   Everything absent from MIRRORED below. This repo is a plugin, not a
//   mirror; the sync only owns files explicitly listed here.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_BASE = 'https://api.sproutgoodhabits.com';

/**
 * Files this script owns: the published guide's filename -> our path.
 *
 * Deliberately an allowlist rather than "mirror the whole index". The server
 * publishes every static guide it registers; this repo wants only the ones it
 * genuinely re-distributes. Adding one is a line here.
 */
const MIRRORED = [{ file: 'canvas/sdk.md', target: 'canvas/sdk.md' }];

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const baseIndex = args.indexOf('--base');
const base = (baseIndex >= 0 ? args[baseIndex + 1] : DEFAULT_BASE).replace(/\/$/, '');

/**
 * Prepended so a human opening the file learns not to hand-edit it, and learns
 * where the real document lives.
 *
 * Carries NO timestamp and no server revision on purpose. Volatile provenance
 * would make every scheduled run produce a diff, and a daily "synced at"
 * commit teaches everyone to ignore this file's history. With only stable
 * text in the banner, a change to this file means exactly one thing: the
 * upstream document changed. When it synced is what git already records.
 */
function banner(sourceUrl) {
  return [
    '<!--',
    '  GENERATED FILE — do not edit by hand.',
    '',
    `  Source of truth: ${sourceUrl}`,
    '  That URL is served by the Sprout server itself, from the same registry',
    '  that answers MCP `resources/read`, so it always describes the server',
    '  that is actually deployed. Edit the doc in sprout-app; this copy is',
    '  regenerated by scripts/sync-sprout-app-docs.mjs.',
    '-->',
    '',
  ].join('\n');
}

/**
 * Refuse to overwrite a good document with something that is not the document.
 *
 * The failure this prevents is the expensive one: a captive portal, a 404
 * body, an error page, or a truncated response replacing a working guide and
 * getting committed. A wrong-looking fetch must fail the run loudly rather
 * than land silently — a stale doc is recoverable, a clobbered one is a
 * revert.
 */
function assertPlausible(file, body) {
  if (body.length < 500) {
    throw new Error(`${file}: response is only ${body.length} bytes — refusing to overwrite.`);
  }
  if (!body.trimStart().startsWith('#')) {
    throw new Error(`${file}: response does not start with a markdown heading — refusing.`);
  }
}

async function fetchGuide(file) {
  const url = `${base}/guides/${file}`;
  const response = await fetch(url, { headers: { accept: 'text/markdown' } });
  if (!response.ok) {
    throw new Error(`${url} responded ${response.status} ${response.statusText}`);
  }
  const body = await response.text();
  assertPlausible(file, body);
  return { url, body };
}

function readIfPresent(target) {
  try {
    return readFileSync(path.join(ROOT, target), 'utf-8');
  } catch {
    return null;
  }
}

let stale = 0;

for (const { file, target } of MIRRORED) {
  const { url, body } = await fetchGuide(file);
  const next = `${banner(url)}${body}`;
  const current = readIfPresent(target);

  if (current === next) {
    console.log(`unchanged  ${target}`);
    continue;
  }

  stale += 1;
  if (checkOnly) {
    console.error(`STALE      ${target} — differs from ${url}`);
    continue;
  }

  writeFileSync(path.join(ROOT, target), next);
  console.log(`updated    ${target} <- ${url}`);
}

if (checkOnly && stale > 0) {
  console.error(
    `\n${stale} file(s) differ from the server. Run: node scripts/sync-sprout-app-docs.mjs`
  );
  process.exit(1);
}
